/**
 * Detect clicks that come from a screen reader (TalkBack, VoiceOver, NVDA…) instead of a finger.
 *
 * Websites cannot ask whether a screen reader is on (the OS hides it for privacy), but the
 * "virtual" clicks they produce look different. These checks follow React Aria
 * (@react-aria/utils isVirtualClick / isVirtualPointerEvent), which are widely used in practice.
 */

function isAndroid(): boolean {
  return typeof navigator !== 'undefined' && /Android/i.test(navigator.userAgent)
}

interface MozMouseEvent extends MouseEvent {
  mozInputSource?: number
}

/** A click that was not produced by a real pointer (screen reader double-tap, or keyboard). */
export function isVirtualClick(event: MouseEvent | PointerEvent): boolean {
  // JAWS/NVDA with Firefox
  if ((event as MozMouseEvent).mozInputSource === 0 && event.isTrusted) return true
  // Android TalkBack: detail varies, but the click reports a pressed button and a pointer type
  const pointerType = (event as PointerEvent).pointerType
  if (isAndroid() && pointerType) return event.type === 'click' && event.buttons === 1
  return event.detail === 0 && !pointerType
}

/** A pointerdown generated by a screen reader rather than a real touch or mouse. */
export function isVirtualPointerEvent(event: PointerEvent): boolean {
  return (
    (!isAndroid() && event.width === 0 && event.height === 0) ||
    (event.width === 1 &&
      event.height === 1 &&
      event.pressure === 0 &&
      event.detail === 0 &&
      event.pointerType === 'mouse')
  )
}

/** A real finger on a touch screen: has a contact area or pressure (screen readers report neither). */
export function isRealTouch(event: PointerEvent): boolean {
  return event.pointerType === 'touch' && (event.width > 1 || event.height > 1 || event.pressure > 0)
}

/**
 * True when this click looks like it came from a screen reader double-tap (not a keyboard).
 * A real finger touch just before the click always wins: then it is never a screen reader.
 */
export function isScreenReaderClick(
  event: MouseEvent,
  lastPointerWasVirtual: boolean,
  lastPointerWasRealTouch = false,
): boolean {
  if (lastPointerWasRealTouch) return false
  if (lastPointerWasVirtual) return true
  if (!isVirtualClick(event)) return false
  // A keyboard Enter/Space click has detail 0 too; only treat it as a screen reader on touch devices.
  return typeof window !== 'undefined' && window.matchMedia?.('(pointer: coarse)').matches === true
}
